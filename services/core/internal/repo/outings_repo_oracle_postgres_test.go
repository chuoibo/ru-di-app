func nilOuting(o *Outing) any {
	if o == nil {
		return nil
	}
	return tOuting(*o)
}

func nilInvite(i *OutingInvite) any {
	if i == nil {
		return nil
	}
	return tOutingInvite(*i)
}

func argTimelineStops(v any) []TimelineStop {
	out := []TimelineStop{}
	for _, item := range v.([]any) {
		stop := item.(map[string]any)
		out = append(out, TimelineStop{MinuteOfDay: argNumber(stop["minute_of_day"]),
			Label: stop["label"].(string), PlaceName: argText(stop["place_name"]),
			PlaceID: argText(stop["place_id"])})
	}
	return out
}

func argItineraryStops(v any) []ItineraryStop {
	out := []ItineraryStop{}
	for _, item := range v.([]any) {
		stop := item.(map[string]any)
		next := ItineraryStop{ID: stop["id"].(string), MinuteOfDay: argNumber(stop["minute_of_day"]),
			Label: stop["label"].(string), PlaceName: argText(stop["place_name"]),
			PlaceID: argText(stop["place_id"]), Day: optionalDay(argText(stop["day"])),
			DurationMinutes: optionalNumber(stop["duration_minutes"]), TimeLocked: true}
		if locked, ok := stop["time_locked"].(bool); ok {
			next.TimeLocked = locked
		}
		if point, ok := stop["meeting_point"].(map[string]any); ok {
			lat, lng := argFloat(point["lat"]), argFloat(point["lng"])
			label := point["label"].(string)
			next.MeetingLat, next.MeetingLng, next.MeetingLabel = &lat, &lng, &label
		}
		out = append(out, next)
	}
	return out
}

// argRawDays reads itinerary_days, which a case writes as JSON text so that
// the key order Python's dicts carry survives the trip through Go.
func argRawDays(v any) []json.RawMessage {
	out := []json.RawMessage{}
	for _, item := range v.([]any) {
		out = append(out, json.RawMessage(item.(string)))
	}
	return out
}

func argExpected(v any) *int64 {
	if v == nil {
		return nil
	}
	n := argNumber(v)
	return &n
}

func outingRepoGoCall(repo Repository, method string, a map[string]any) (any, error) {
	s := func(key string) string { return argString(a, key) }
	now := func() time.Time { return argInstant(s("now")) }
	if strings.HasPrefix(method, "route.") {
		return outingRouteGo(repo, method, a)
	}
	switch method {
	case "get_outing":
		o, err := repo.GetOuting(bg, s("outing_id"))
		return nilOuting(o), err
	case "list_outings":
		rows, err := repo.ListOutings(bg, s("context_id"))
		items := []any{}
		for _, row := range rows {
			items = append(items, tOuting(row))
		}
		return tSeq(items), err
	case "get_outing_stop":
		stop, outing, err := repo.GetOutingStop(bg, s("stop_id"))
		if err != nil || stop == nil {
			return nil, err
		}
		return tSeq([]any{tOutingStopRecord(*stop), tOuting(*outing)}), nil
	case "list_outing_checkins":
		rows, err := repo.ListOutingCheckins(bg, s("outing_id"))
		items := []any{}
		for _, row := range rows {
			items = append(items, tStopCheckin(row))
		}
		return tSeq(items), err
	case "create_stop_checkin":
		c, err := repo.CreateStopCheckin(bg, s("stop_id"), s("person_id"), now())
		return tStopCheckin(c), err
	case "replace_outing_stops":
		o, err := repo.ReplaceOutingStops(bg, s("outing_id"), argTimelineStops(a["stops"]),
			argExpected(a["expected_revision"]))
		return tOuting(o), err
	case "replace_outing_itinerary":
		o, err := repo.ReplaceOutingItinerary(bg, s("outing_id"), argItineraryStops(a["stops"]),
			argRawDays(a["itinerary_days"]), argNumber(a["expected_revision"]))
		return tOuting(o), err
	case "create_outing_invite":
		i, err := repo.CreateOutingInvite(bg, OutingInviteInput{OutingID: s("outing_id"), Source: s("source"),
			InvitedPersonID: argText(a["invited_person_id"]), InvitedByID: s("invited_by_id"),
			TokenDigest: digestOf(s("token")), ExpiresAt: argInstant(s("expires_at")), Now: now()})
		return tOutingInvite(i), err
	case "find_outing_invite_for_person":
		i, err := repo.FindOutingInviteForPerson(bg, s("outing_id"), s("person_id"))
		return nilInvite(i), err
	case "get_outing_invite":
		i, err := repo.GetOutingInvite(bg, s("invite_id"))
		return nilInvite(i), err
	case "get_outing_invite_by_digest":
		i, err := repo.GetOutingInviteByDigest(bg, digestOf(s("token")))
		return nilInvite(i), err
	case "accept_outing_invite":
		i, err := repo.AcceptOutingInvite(bg, s("invite_id"), s("accepted_by_id"), now())
		return tOutingInvite(i), err
	case "revoke_outing_invite":
		i, err := repo.RevokeOutingInvite(bg, s("invite_id"), now())
		return tOutingInvite(i), err
	case "rotate_outing_invite_digest":
		i, err := repo.RotateOutingInviteDigest(bg, s("invite_id"), digestOf(s("token")),
			argInstant(s("expires_at")), now())
		return tOutingInvite(i), err
	case "ensure_invited_membership":
		m, err := repo.EnsureInvitedMembership(bg, s("context_id"), s("person_id"), s("invited_by_id"),
			s("origin"), now())
		return tMembership(m), err
	}
	return photoGoCall(repo, method, a)
}

func runOutingGoCase(t *testing.T, pool *pgxpool.Pool, c oracleCase) []any {
	t.Helper()
	tx, err := pool.Begin(bg)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = tx.Rollback(bg) }()
	for _, sql := range c.Setup {
		if _, err := tx.Exec(bg, sql); err != nil {
			t.Fatalf("setup: %v\n%s", err, sql)
		}
	}
	steps := []any{}
	for _, step := range c.Steps {
		for _, sql := range step.Before {
			if _, err := tx.Exec(bg, sql); err != nil {
				t.Fatalf("before: %v\n%s", err, sql)
			}
		}
		rec := &recorder{Querier: tx}
		value, err := outingRepoGoCall(Repository{Q: rec}, step.Call, step.Args)
		statements := []any{}
		for _, sql := range rec.log {
			statements = append(statements, normalizeSQL(sql))
		}
		out := map[string]any{"result": nil, "error": nil, "warnings": []any{}, "statements": statements,
			"probes": nil}
		if err != nil {
			out["error"] = pairRepoGoError(err)
			steps = append(steps, generic(t, out))
			break
		}
		out["result"] = value
		probes := []any{}
		for _, sql := range step.Probes {
			rows, err := tx.Query(bg, sql)
			if err != nil {
				t.Fatalf("probe: %v\n%s", err, sql)
			}
			texts, err := pgx.CollectRows(rows, pgx.RowTo[string])
			if err != nil {
				t.Fatal(err)
			}
			probes = append(probes, append([]string{}, texts...))
		}
		out["probes"] = probes
		steps = append(steps, generic(t, out))
	}
	return steps
}

// normalizeOutingSteps is normalizePairSteps for probeOutingRowLocks.
func normalizeOutingSteps(steps []any, c oracleCase) []any {
	spec, _ := json.Marshal(c)
	known := map[string]bool{}
	for _, id := range uuidText.FindAllString(string(spec), -1) {
		known[id] = true
	}
	out := make([]any, len(steps))
	for i, step := range steps {
		out[i] = step
		probes, _ := step.(map[string]any)["probes"].([]any)
		for j, probe := range c.Steps[i].Probes {
			if j >= len(probes) {
				continue
			}
			rows, ok := probes[j].([]any)
			if !ok {
				continue
			}
			switch probe {
			case probeOutingRowLocks:
				masked := make([]string, len(rows))
				for k, row := range rows {
					masked[k] = uuidText.ReplaceAllStringFunc(row.(string), func(id string) string {
						if known[id] {
							return id
						}
						return "<generated>"
					})
				}
				sort.Strings(masked)
				sorted := make([]any, len(masked))
				for k, row := range masked {
					sorted[k] = row
				}
				probes[j] = sorted
			case probeNow:
				if len(rows) == 1 {
					if now, ok := rows[0].(string); ok && now != "" {
						out[i] = replaceText(out[i], now, transactionNow)
					}
				}
			}
		}
	}
	return out
}

