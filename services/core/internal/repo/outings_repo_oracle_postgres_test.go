func TestOutingRowLocksSerialiseRequests(t *testing.T) {
	image := os.Getenv("CORE_PYTHON_IMAGE")
	if image == "" {
		t.Skip("CORE_PYTHON_IMAGE not set; see the comment at the top of outings_repo_oracle_postgres_test.go")
	}
	pool, _ := migratedOracleSchema(t, image, "outing_locks_")
	w := newOutingWorld()
	for _, sql := range w.sql {
		if _, err := pool.Exec(bg, sql); err != nil {
			t.Fatalf("seed: %v\n%s", err, sql)
		}
	}
	now := argInstant(outingNow)
	begin := func(t *testing.T, lockTimeout string) pgx.Tx {
		t.Helper()
		tx, err := pool.Begin(bg)
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { _ = tx.Rollback(context.Background()) })
		if lockTimeout != "" {
			if _, err := tx.Exec(bg, "SET LOCAL lock_timeout = '"+lockTimeout+"'"); err != nil {
				t.Fatal(err)
			}
		}
		return tx
	}

	t.Run("an arrival holds the trip against a second arrival and against a save", func(t *testing.T) {
		first := begin(t, "")
		if _, err := (Repository{Q: first}).CreateStopCheckin(bg, w.s1, w.an, now); err != nil {
			t.Fatal(err)
		}
		if _, err := (Repository{Q: begin(t, "150ms")}).CreateStopCheckin(bg, w.s3, w.an, now); !lockNotAvailable(err) {
			t.Fatalf("an arrival at another stop of the same trip did not wait: %v", err)
		}
		if _, err := (Repository{Q: begin(t, "150ms")}).ReplaceOutingStops(bg, w.oMulti, nil, nil); !lockNotAvailable(err) {
			t.Fatalf("saving the plan did not wait on the arrival: %v", err)
		}
		if _, err := (Repository{Q: begin(t, "150ms")}).GetOuting(bg, w.oMulti); err != nil {
			t.Fatalf("a plain read must not wait: %v", err)
		}
	})

	t.Run("two saves of one plan serialise, and the loser sees the new revision", func(t *testing.T) {
		first := begin(t, "")
		revision := int64(4)
		if _, err := (Repository{Q: first}).ReplaceOutingStops(bg, w.oMulti, []TimelineStop{
			{MinuteOfDay: 480, Label: "Một mình (dữ liệu mẫu)"}}, &revision); err != nil {
			t.Fatal(err)
		}
		second := begin(t, "")
		done := make(chan error, 1)
		go func() {
			_, err := (Repository{Q: second}).ReplaceOutingStops(bg, w.oMulti, nil, &revision)
			done <- err
		}()
		select {
		case err := <-done:
			t.Fatalf("the second save did not wait for the first: %v", err)
		case <-time.After(300 * time.Millisecond):
		}
		if err := first.Commit(bg); err != nil {
			t.Fatal(err)
		}
		var conflict *Conflict
		if err := <-done; !errors.As(err, &conflict) || conflict.Code != "TIMELINE_REVISION_CONFLICT" {
			t.Fatalf("the second save, after the first committed: %v", err)
		}
	})

	t.Run("two redemptions of one link end as one acceptance", func(t *testing.T) {
		first := begin(t, "")
		if _, err := (Repository{Q: first}).AcceptOutingInvite(bg, w.invLink, w.ngoai, now); err != nil {
			t.Fatal(err)
		}
		second := begin(t, "")
		done := make(chan error, 1)
		go func() {
			_, err := (Repository{Q: second}).AcceptOutingInvite(bg, w.invLink, w.binh, now)
			done <- err
		}()
		select {
		case err := <-done:
			t.Fatalf("the second redemption did not wait for the first: %v", err)
		case <-time.After(300 * time.Millisecond):
		}
		if err := first.Commit(bg); err != nil {
			t.Fatal(err)
		}
		var conflict *Conflict
		if err := <-done; !errors.As(err, &conflict) || conflict.Code != "OUTING_INVITE_ALREADY_ACCEPTED" {
			t.Fatalf("the second redemption, after the first committed: %v", err)
		}
		var holder string
		if err := pool.QueryRow(bg, `SELECT accepted_by_id::text FROM outing_invites WHERE id = $1::UUID`,
			w.invLink).Scan(&holder); err != nil {
			t.Fatal(err)
		}
		if holder != w.ngoai {
			t.Fatalf("the link was spent by %s", holder)
		}
	})
}
