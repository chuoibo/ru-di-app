// Differential test of the W7 repository methods (a trip's plan, its arrivals
// and its invitations) against the real SqlAlchemyApiRepository, driven
// through scripts/render_w7_repo_oracle.py. Same design as
// pair_repo_oracle_postgres_test.go, whose case format, value tags, statement
// normalisation, conflict tagging, row lock probe and comparison it reuses.
//
// What this wave has to pin that the earlier ones did not: two of the methods
// are a SQLAlchemy unit of work rather than a statement, so what is compared
// is not only which rows moved but the order the flush moved them in -- the
// parking pass that keeps uq_outing_stops_position satisfied while a plan is
// permuted, the parent table going first, and the SET list of each UPDATE
// carrying exactly the columns whose value changed.
//
// Invitations are the second sharp edge. The server stores a digest, never a
// token, so the fixture writes sha256 of a short sample word computed inside
// PostgreSQL and every case hands both sides that same word. The Python
// driver also pins secrets.token_urlsafe for a route step, so the digest the
// two sides write is the digest of one token and the table dump can compare
// it byte for byte.
//
// TestOutingRowLocksSerialiseRequests is Go only: the races the Python
// branches name (two arrivals at one stop, two saves of one plan, two
// redemptions of one link).
//
// Without CORE_PYTHON_IMAGE both tests skip; scripts/go_postgres_tier.sh sets
// it and refuses skips.

